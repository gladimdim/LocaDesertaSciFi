// ── images ───────────────────────────────────────────────────────────────
const mediaUrl = (rel: string) => "/media/" + rel.split("/").map(encodeURIComponent).join("/")
let assets: string[] | undefined
const allAssets = () => (assets ??= listAssets("content").map((a) => a.split("\\").join("/")))

/** /media/x/y.png → /thumbs/<w>/x/y.webp (generated by the thumbs integration) */
export const thumb = (url: string | undefined, w: 480 | 1280 = 480) =>
  url?.startsWith("/media/") ? `/thumbs/${w}/` + url.slice(7).replace(/\.(png|jpe?g|webp)$/i, ".webp") : url

export function coverOf(n: Note, notes?: Note[]): string | undefined {
  const dir = n.filePath?.replace(/^content\//, "").split("/").slice(0, -1).join("/") ?? ""
  const own = allAssets().find((a) => a.startsWith(dir + "/") && /^cover\.(jpe?g|png|webp)$/i.test(a.slice(dir.length + 1)))
  if (own) return mediaUrl(own)
  if (n.data.thumbnail) return n.data.thumbnail
  if (n.data.cover && /cover/i.test(n.data.cover)) return n.data.cover
  if (notes) {
    for (const id of Object.values(n.data.translations)) {
      const t = notes.find((o) => o.id === id)
      if (t && t !== n) {
        const c = coverOf(t)
        if (c && !c.includes("/Ships/Hetmanate_Patrol")) return c
      }
    }
  }
  return n.data.cover
}
export const imageOf = (n: Note, notes?: Note[]) => coverOf(n, notes) ?? FALLBACK[factionOf(n.id)]

// ── folders ──────────────────────────────────────────────────────────────
export interface Folder {
  id: string
  name: string
  lang: Lang
  note?: Note // folder note (X/X.md) or index.md
  notes: Note[] // direct children (excluding the folder note)
  folders: string[] // direct sub-folder ids
}

let folderCache: Map<string, Folder> | undefined
export async function folders() {
  if (folderCache) return folderCache
  const notes = await allNotes()
  const map = new Map<string, Folder>()
  const ensure = (id: string): Folder => {
    let f = map.get(id)
    if (!f) {
      const top = id.split("/")[0]
      f = { id, name: id.split("/").pop()!.replace(/-/g, " "), lang: top === "en" || top === "de" ? (top as Lang) : "uk", notes: [], folders: [] }
      map.set(id, f)
      const parent = id.includes("/") ? id.slice(0, id.lastIndexOf("/")) : ""
      if (parent) {
        const p = ensure(parent)
        if (!p.folders.includes(id)) p.folders.push(id)
      }
    }
    return f
  }
  for (const n of notes) {
    if (!n.data.folder) continue
    const f = ensure(n.data.folder)
    if (n.data.isFolderNote || n.data.isIndex) f.note = n
    else f.notes.push(n)
  }
  for (const f of map.values()) if (f.note) f.name = displayTitle(f.note)
  folderCache = map
  return map
}

/** where a folder link should go: its folder note if there is one, else the folder page */
export const folderHref = (f: Folder) => (f.note && !f.note.data.isIndex ? noteUrl(f.note.id) : noteUrl(f.id))

export async function crumbs(n: Note) {
  const fs = await folders()
  const parts = n.id.split("/")
  const out: { name: string; href: string }[] = []
  for (let i = 1; i < parts.length; i++) {
    const id = parts.slice(0, i).join("/")
    if (id === "en" || id === "de") continue
    const f = fs.get(id)
    if (f && f.note?.id !== n.id) out.push({ name: f.name, href: noteUrl(f.id) })
  }
  return out
}

// ── links ────────────────────────────────────────────────────────────────
let backCache: Map<string, Note[]> | undefined
export async function backlinks(n: Note) {
  if (!backCache) {
    backCache = new Map()
    const notes = await allNotes()
    const ids = new Set(notes.map((x) => x.id))
    for (const src of notes) {
      const seen = new Set<string>()
      for (const m of src.body?.matchAll(/\]\((\/[^)#\s]*)/g) ?? []) {
        let id: string
        try {
          id = decodeURIComponent(m[1]).replace(/^\/|\/$/g, "") || "index"
        } catch {
          continue
        }
        if (id === src.id || seen.has(id) || !ids.has(id)) continue
        seen.add(id)
        backCache.set(id, [...(backCache.get(id) ?? []), src])
      }
    }
  }
  return backCache.get(n.id) ?? []
}

/** lang → note id of every version of this note (both directions of `translations`) */
export async function translations(n: Note) {
  const notes = await allNotes()
  const out: Partial<Record<Lang, string>> = { [n.data.lang]: n.id }
  for (const [l, id] of Object.entries(n.data.translations)) if (notes.some((o) => o.id === id)) out[l as Lang] = id
  for (const o of notes) if (Object.values(o.data.translations).includes(n.id)) out[o.data.lang] ??= o.id
  return out
}

// ── books ────────────────────────────────────────────────────────────────
export async function books(lang: Lang) {
  const notes = await allNotes()
  const all = notes.filter((n) => n.data.section === "Books" && n.data.isFolderNote)
  const mine = all.filter((n) => n.data.lang === lang)
  const covered = new Set<string>()
  for (const b of mine) for (const id of Object.values(await translations(b))) covered.add(id!)
  // untranslated books from other languages, so every language shows the whole shelf
  const rest = all.filter((n) => n.data.lang !== lang && !covered.has(n.id) && !(lang === "de" && n.data.lang === "uk" && all.some((e) => e.data.lang === "en" && Object.values(e.data.translations).includes(n.id))))
  const order = (n: Note) => wordCount(n)
  return [...mine.sort((a, b) => order(b) - order(a)), ...rest.sort((a, b) => order(b) - order(a))]
}

export const isBook = (n: Note) => n.data.section === "Books" && n.data.isFolderNote

// ── timeline (parsed from the chronology table) ──────────────────────────
export interface Event {
  era: string
  old: string
  text: string
  key: boolean
}
export function timeline(n: Note): Event[] {
  const rows: Event[] = []
  for (const line of n.body.split("\n")) {
    const cells = line.split("|").map((c) => c.trim())
    if (cells.length < 5 || /^[-: ]+$/.test(cells[1]) || /^(ЗЕ|SE|SE year|Year)$/i.test(cells[1])) continue
    const text = cells[3]
    if (!text || /^-+$/.test(text)) continue
    rows.push({ era: cells[1], old: cells[2], text, key: /\*\*/.test(text) })
  }
  return rows
}
