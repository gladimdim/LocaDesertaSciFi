// ── tags ─────────────────────────────────────────────────────────────────
export const tagSlug = (t: string) => t.toLowerCase().trim().replace(/\s+/g, "-")
export async function tagIndex() {
  const map = new Map<string, { label: string; notes: Note[] }>()
  for (const n of await allNotes())
    for (const t of n.data.tags) {
      const k = tagSlug(t)
      if (!map.has(k)) map.set(k, { label: t.toLowerCase(), notes: [] })
      map.get(k)!.notes.push(n)
    }
  return [...map.entries()].sort((a, b) => b[1].notes.length - a[1].notes.length || a[0].localeCompare(b[0]))
}

