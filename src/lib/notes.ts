/** children of a folder as card data: sub-folders first, then notes */
export async function folderItems(f: Folder, notes?: Note[]) {
  const fs = await folders()
  const subs = f.folders.map((id) => fs.get(id)!).filter(Boolean)
  const all = notes ?? (await allNotes())
  // a folder shows one of its notes' artwork, picked by a hash of its id so neighbours differ
  const imgOfFolder = (sf: Folder): string | undefined => {
    const pics: string[] = []
    const collect = (x: Folder) => {
      for (const n of [...(x.note ? [x.note] : []), ...x.notes]) {
        const c = coverOf(n, all)
        if (c && !pics.includes(c)) pics.push(c)
      }
      x.folders.forEach((id) => collect(fs.get(id)!))
    }
    collect(sf)
    if (sf.note && coverOf(sf.note, all)) return coverOf(sf.note, all)
    const h = [...sf.id].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7)
    return pics.length ? pics[h % pics.length] : undefined
  }
  const count = (sf: Folder): number => sf.notes.length + (sf.note ? 1 : 0) + sf.folders.reduce((a, id) => a + count(fs.get(id)!), 0)
  // the folder's own note (e.g. the book itself in Books/X/X.md) comes first
  const own = f.note && !f.note.data.isIndex ? [f.note] : []
  return [
    ...own.map((n) => ({ href: noteUrl(n.id), title: displayTitle(n), image: coverOf(n, all), text: summary(n, 120), count: 0, folder: false, faction: factionOf(n.id) })),
    ...subs
      .sort((a, b) => a.name.localeCompare(b.name, "uk"))
      .map((sf) => ({ href: noteUrl(sf.id), title: sf.name, image: imgOfFolder(sf), text: sf.note ? summary(sf.note, 120) : undefined, count: count(sf), folder: true, faction: factionOf(sf.id) })),
    ...f.notes
      .sort((a, b) => displayTitle(a).localeCompare(displayTitle(b), "uk"))
      .map((n) => ({ href: noteUrl(n.id), title: displayTitle(n), image: coverOf(n, all), text: summary(n, 120), count: 0, folder: false, faction: factionOf(n.id) })),
  ]
}

/** rendered note HTML with artwork served as lazy WebP (full size kept for the lightbox) */
export const articleHtml = (n: Note) =>
  (n.rendered?.html ?? "").replace(/<img\s([^>]*?)src="(\/media\/[^"]+\.(?:png|jpe?g))"([^>]*)>/gi, (_m, a: string, src: string, b: string) => {
    const rest = (a + b).replace(/\sloading="[^"]*"/, "")
    return `<img ${rest.trim()} src="${thumb(src, 1280)}" data-full="${src}" data-zoom loading="lazy" decoding="async">`
  })
export const headingsOf = (n: Note) =>
  ((n.rendered?.metadata?.headings ?? []) as { depth: number; slug: string; text: string }[])
